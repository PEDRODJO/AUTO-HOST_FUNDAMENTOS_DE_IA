const router = require('express').Router();
const auth = require('../controllers/authController');
const data = require('../controllers/dataController');
const clients = require('../controllers/clientsController');
const roles = require('../controllers/rolesController');
const sepomex = require('../controllers/sepomexController');
const workshops = require('../controllers/workshopController');
const vehicles = require('../controllers/vehicleController');
const { workshopPhotoUpload } = require('../middleware/workshopUpload');
const { vehiclePhotoUpload } = require('../middleware/vehicleUpload');
const { authenticate, requireAdmin, requireVehicleAccess } = require('../middleware/auth');
router.post('/auth/login', auth.login);
router.post('/auth/register', auth.register);
router.post('/auth/recovery', auth.requestReset);
router.post('/auth/reset', auth.resetPassword);
router.get('/sepomex/:cp', sepomex.byPostalCode);
router.get('/me', authenticate, (req, res) => res.json({ user: req.user }));
router.get('/customers', authenticate, data.customers);
router.get('/clients/workshops', authenticate, requireAdmin, clients.workshops);
router.get('/clients/vehicle-assignment', authenticate, requireVehicleAccess, clients.vehicleAssignmentClients);
router.get('/workshops', authenticate, requireAdmin, workshops.listWorkshops);
router.put('/workshops/:id', authenticate, requireAdmin, workshopPhotoUpload, workshops.updateWorkshop);
router.delete('/workshops/:id', authenticate, requireAdmin, workshops.softDeleteWorkshop);
router.get('/vehicles/photos/:filename', authenticate, requireVehicleAccess, vehicles.photo);
router.get('/vehicles/mechanics', authenticate, requireVehicleAccess, vehicles.mechanics);
router.get('/vehicles', authenticate, requireVehicleAccess, vehicles.list);
router.post('/vehicles', authenticate, requireVehicleAccess, vehiclePhotoUpload, vehicles.create);
router.put('/vehicles/:id', authenticate, requireVehicleAccess, vehiclePhotoUpload, vehicles.update);
router.delete('/vehicles/:id', authenticate, requireVehicleAccess, vehicles.remove);
router.get('/clients', authenticate, requireAdmin, clients.list);
router.post('/clients', authenticate, requireAdmin, clients.create);
router.put('/clients/:id', authenticate, requireAdmin, clients.update);
router.delete('/clients/:id', authenticate, requireAdmin, clients.remove);
router.get('/clients/:id/vehicles', authenticate, requireVehicleAccess, clients.vehicleOptions);
router.put('/clients/:id/vehicles', authenticate, requireVehicleAccess, clients.associateVehicle);
router.get('/roles', authenticate, roles.list);
router.post('/roles', authenticate, requireAdmin, roles.create);
router.put('/roles/:id', authenticate, requireAdmin, roles.update);
router.delete('/roles/:id', authenticate, requireAdmin, roles.suspend);
module.exports = router;
